import assert from 'node:assert/strict';
import { planSourceLookup, executeSourceLookup } from './source-router.mjs';
import { buildKnowledgeMap, selectKnowledgeSlots } from './knowledge-map.mjs';
const profile = { venues: { 东坝: { venueId: 'DONGBA' }, 中影: { venueId: 'ZHONGYING' } } };
const input = text => ({ query: { text }, scope: { venueIds: ['DONGBA'] } });
const now = new Date('2026-09-06T01:00:00Z');
const plan = planSourceLookup(input('查9月2号东坝店销售额是多少'),profile,now);
assert.equal(plan.date,'2026-09-02'); assert.equal(plan.capabilityId,'channel_daily');
assert.equal(planSourceLookup(input('查9月2号东大店销售额'),profile,now).status,'clarification');
assert.equal(planSourceLookup(input('查2月30日东坝销售额'),profile,now).status,'clarification');
assert.equal(planSourceLookup(input('查9月2日到9月3日东坝销售额'),profile,now).status,'clarification');
assert.equal(planSourceLookup(input('我今天不想上班'),profile,now),null);
assert.equal(planSourceLookup(input('查9月2日东坝触达人数'),profile,now).capabilityId,'daily_traffic');
const reads = [];
const deps = { now: 0, sources: { channel_daily: { token: 'fixture', title: 'fixture', dateHeader: '日期', sheets: () => [{ id:'s1' },{ id:'s2' }], value: row => row['销售额'] } }, parseDate: String, parseNumber: v => v == null || v === '' ? null : Number(v), readRange: async (_,range) => {
  reads.push(range);
  if (range.endsWith('A1:Z1')) return [['日期','销售额']];
  if (range.endsWith('A2:A5001')) return [['2026-09-01'],['2026-09-02']];
  assert.ok(range.endsWith('A3:Z3')); return [['2026-09-02',range.startsWith('s1') ? 12 : 8]];
} };
const result = await executeSourceLookup(plan,deps);
assert.equal(result.core.box_office_total,20); assert.equal(result.budget.calls,6);
reads.length = 0;
assert.equal((await executeSourceLookup(plan,deps)).budget.calls,2);
const missing = await executeSourceLookup(plan,{ ...deps, readRange: async () => [['2026-09-02','']] });
assert.equal(missing.status,'incomplete'); assert.equal(missing.core.box_office_total,null);
const scope = { projectId:'p',venueNames:['东坝','中影'] };
const knowledge = { gaps:[], implicitItems:[] };
let map = buildKnowledgeMap(knowledge,scope,'finance');
assert.deepEqual(selectKnowledgeSlots(map,knowledge).map(s=>s.dimensionId),['identity']);
knowledge.implicitItems.push({ id:'e',status:'confirmed',dimensionId:'identity',facetId:'audience',scope,statement:'fixture' });
map = buildKnowledgeMap(knowledge,scope,'finance');
assert.equal(map.cells.find(c=>c.id==='identity').status,'partial');
assert.deepEqual(map.cells.find(c=>c.id==='identity').coverage,{covered:1,total:4});
assert.ok(selectKnowledgeSlots(map,knowledge).some(s=>s.dimensionId==='goals'));
assert.ok(selectKnowledgeSlots(map,knowledge).some(s=>s.dimensionId==='identity' && s.facetId==='core_value'));
assert.ok(!selectKnowledgeSlots(map,knowledge).some(s=>s.dimensionId==='economics'));
const limited = buildKnowledgeMap({ ...knowledge,implicitItems:[{ ...knowledge.implicitItems[0],scope:{projectId:'p',venueNames:['东坝']} }] },scope);
assert.equal(limited.coverage.documented,0);
knowledge.implicitItems.push({ id:'r',status:'confirmed',dimensionId:'role_goals',roleId:'finance',scope });
assert.equal(buildKnowledgeMap(knowledge,scope,'growth').cells.find(c=>c.id==='role_goals').status,'unknown');
console.log(JSON.stringify({ status:'passed', checks:['date and ambiguity','personal no retrieval','two source routing','bounded row reads and index cache','missing is not zero','knowledge facets are partial and deepen','knowledge dependency','scope and role isolation'] }));
